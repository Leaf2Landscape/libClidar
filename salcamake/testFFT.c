/*############################################*/
/*track smoothed features*/

void trackFeatures(float *smoothed,int nLength,funcFit *fun)
{
  int i=0,cent=0;
  char within=0;
  float integral=0;
  float max=0;

  max=-100.0;
  for(i=0;i<nLength;i++){
    if(smoothed[i]>TOL){
      if(!within)within=1;
      integral+=smoothed[i]*fun->sRes;
      if(smoothed[i]>max){
        max=smoothed[i];
        cent=i;
      }
    }else if((smoothed[i]<=TOL)&&within){
      fprintf(stdout,"%f %f\n",(float)cent*fun->sRes,integral);
      integral=0.0;
      within=0;
      max=-100.0;
    }
  }
  return;
}/*trackFeatures*/


/*############################################*/
/*smooth waveform*/

float *smoothFFT(char *data,int length,funcFit *fun)
{
  int i=0,place1=0,place2=0;
  float res=0;
  float *smoothFF=NULL;
  float *smoothed=NULL;
  float *resampled=NULL;
  float *reSample(char *,int,float,funcFit *);
  float newEnergy=0;
  char thresh=0;
  void four1(float *,unsigned long,int);


  res=0.15;  /*SALCA resolution*/
  thresh=-110;


  resampled=reSample(data,length,res,fun);
  four1(resampled,fun->nLength,1);
  smoothFF=falloc(2*fun->nLength+2,"smoothed fourier",0);

  /*smooth by multiplication of complex arrays*/
  for(i=0;i<fun->nLength;i++){
    place1=i*2+1;
    place2=i*2+2;
    smoothFF[place1]=resampled[place1]*fun->smoother[place1]-resampled[place2]*fun->smoother[place2];
    smoothFF[place2]=resampled[place1]*fun->smoother[place2]+resampled[place2]*fun->smoother[place1];
  }
  TIDY(resampled);
  four1(smoothFF,fun->nLength,-1);   /*inverse fourier*/

  /*determine new energy*/
  newEnergy=0.0;
  for(i=0;i<fun->nLength;i++)newEnergy+=smoothFF[i]*fun->sRes;

  smoothed=falloc(fun->nLength,"smoothed",0);  /*copy back into real array*/
  for(i=0;i<fun->nLength;i++){
    place1=i*2+1;
    place2=i*2+2;
    smoothed[i]=smoothFF[place1]*fun->energy/newEnergy;
  }
  TIDY(smoothFF);

  return(smoothed);
}/*smoothFFT*/


/*############################################*/
/*resample and get into complex numbers*/

float *reSample(char *data,int length,float res,funcFit *fun)
{
  int i=0,bin=0;
  int arrLen=0,place=0;
  float *resampled=NULL;

  fun->energy=0.0;
  arrLen=2*fun->nLength+2;
  resampled=falloc(2*fun->nLength+2,"resampled",0);
  for(i=0;i<fun->nLength;i++){
    place=2*i+2;
    if((place<0)||(place>=arrLen)){
      fprintf(stderr,"Overstepped bound %d of %d iter %d of %d\n",place,arrLen,i,fun->nLength);
      exit(1);
    }
    resampled[2*i+1]=resampled[2*i+2]=0.0;
  }

  for(i=0;i<length;i++){
    bin=(int)((float)i*res/fun->sRes);
    place=2*bin+1;
    if((place<0)||(place>=arrLen)){
      fprintf(stderr,"Overstepped bound %d of %d\n",place,arrLen);
      exit(1);
    }
    resampled[2*bin+1]=(float)data[i]-(float)backSig;
    fun->energy+=((float)data[i]-(float)backSig)*res;
  }
  return(resampled);
}/*reSample*/


/*############################################*/
/*smooth waveform*/

float *smooth(char *data,int length,funcFit *fun)
{
  int i=0,j=0,place=0;
  int resDif=0;
  float *smoothed=NULL;
  float res=0,contN=0;
  char thresh=0;
 
  res=0.15;  /*SALCA resolution*/
  thresh=-110;

  smoothed=falloc(fun->nLength,"smoothed",0);

  if(fun->sWidth<TOL){    /*no smoothing, just denoise*/
    for(i=0;i<length;i++){
      place=i*resDif;
      if(data[i]>=thresh)smoothed[place]=(float)data[i]-(float)backSig;
      else               smoothed[place]=0.0;
    }
  }else{
    for(i=0;i<fun->nLength;i++)smoothed[i]=0.0;
    for(i=0;i<length;i++){
      if(data[i]>thresh){  /*there is signal, add to arrays*/

        /*first calculate energy in the Guassian, should be 1 plus rounding issues*/
        contN=0.0;
        for(j=0;j<fun->sLength;j++){
          place=(int)(((float)i*res+(float)(j-fun->sLength/2)*fun->sRes)/fun->sRes+0.5);
          if((place>=0)&&(place<fun->nLength)){
            contN+=fun->smoother[j];
          }
        }

        /*add up energy, normalising for Gaussian rounding issues*/
        for(j=0;j<fun->sLength;j++){
          place=(int)(((float)i*res+(float)(j-fun->sLength/2)*fun->sRes)/fun->sRes+0.5);
          if((place>=0)&&(place<fun->nLength)){
            smoothed[place]+=((float)data[i]-(float)backSig)*fun->smoother[j]/contN;
          }
        }
      }
    }
  }
  return(smoothed);
}/*smooth*/


/*############################################*/
/*set up function for fitting*/

funcFit *setFunction(float sWidth,float sRes,int length)
{
  funcFit *fun=NULL;
  float resDif=0,res=0;
  float test=0;
  void setSmoother(funcFit *);
  void setFFTsmooth(funcFit *);

  res=0.15;

  if(!(fun=(funcFit *)calloc(1,sizeof(funcFit)))){
    fprintf(stderr,"error in function fitting structure.\n");
    exit(1);
  }
  fun->sWidth=sWidth;
  fun->sRes=sRes;  /*fifth of SALCA's resolution*/

  if(fun->sWidth>TOL){
    //setSmoother(fun);
    resDif=(int)(res/fun->sRes+0.5);
    fun->nLength=length*resDif;

    /*check it's a power of 2*/
    test=log((double)fun->nLength)/log(2.0)-(int)(log((double)fun->nLength)/log(2.0)+0.5);
    if((test>TOL)||(test<-TOL)){  /*not a power of 2, pad*/
      fun->nLength=pow(2.0,(float)((int)(log((float)length*resDif)/log(2.0)+0.5)+1));
    }
    setFFTsmooth(fun);
  }

  return(fun);
}/*setFunction*/


/*############################################*/
/*make FFT'd pulse for smoothing*/

void setFFTsmooth(funcFit *fun)
{
  int i=0;
  int place=0,arrLen=0;
  float x=0,end=0;
  void four1(float *,unsigned long,int);

  end=(float)fun->nLength*fun->sRes;

  arrLen=2*(fun->nLength+1);
  fun->smoother=falloc(arrLen,"smoother",0);
  for(i=0;i<fun->nLength;i++){
    x=(float)i*fun->sRes;
    place=2*i+2;
    if((place<0)||(place>=arrLen)){
      fprintf(stderr,"Error\n");
      exit(1);
    }
    fun->smoother[2*i+1]=(float)(gaussian((double)x,(double)fun->sWidth,0.0)+gaussian((double)x,(double)fun->sWidth,(double)end)); /*real*/
    fun->smoother[2*i+2]=0.0;  /*imaginary*/
  }

  /*FFT it*/
  four1(fun->smoother,fun->nLength,1);


  return;
}/*setFFTsmooth*/


/*################################################*/
/*make smoothing function*/

void setSmoother(funcFit *fun)
{
  int i=0;
  float x=0,y=0;
  float mu=0;
  float minY=0;

  minY=0.0001;

  /*determine length*/
  for(i=0;;i++){
    x=(float)i*fun->sRes;
    y=(float)gaussian((double)x,(double)fun->sWidth,0.0);
    if(y<minY)break;
  }
  fun->sLength=2*i;
  fun->smoother=falloc(fun->sLength,"smoother",0);

  mu=fun->sRes*(float)i;
  for(i=0;i<fun->sLength;i++){
    x=(float)i*fun->sRes;
    fun->smoother[i]=(float)gaussian((double)x,(double)fun->sWidth,(double)mu);
  }
  return;
}/*setSmoother*/


